def _site_rule(site: str) -> str:
    """Normalize a site rule: strip protocol/www, keep domain-ish token."""
    s = site.strip().lower()
    s = re.sub(r"^https?://", "", s)
    s = re.sub(r"^www\.", "", s)
    s = s.split("/")[0].split("?")[0]
    return s


def build_plugin(name: str, site: str, ctype: str, pattern: str) -> dict:
    """Generate plugin folder + files. Returns {ok, message, name?}."""
    # validate
    if not re.fullmatch(r"[A-Za-z0-9_-]{2,40}", name or ""):
        return {"ok": False, "message": "اسم پلاگین نامعتبره (فقط حروف، عدد، - و _)"}
    if ctype not in TEMPLATES:
        return {"ok": False, "message": "نوع محتوا نامعتبره"}
    rule = _site_rule(site)
    if not rule:
        return {"ok": False, "message": "دامنه سایت نامعتبره"}
    try:
        re.compile(pattern)
    except re.error as e:
        return {"ok": False, "message": f"الگوی regex نامعتبره: {e}"}

    template = TEMPLATES[ctype]
    # Embed the pattern as a raw string literal. To be safe against any quote in
    # the pattern, we emit it via json.dumps (escapes quotes/backslashes properly)
    # into a normal double-quoted string — but patterns often contain \" which
    # would break the literal. So use json.dumps of the pattern itself as the
    # Python literal: json.dumps returns a valid Python string literal.
    code = template.replace("PATTERN_PLACEHOLDER", json.dumps(pattern))
    # SITE_RULE is plain (no quotes expected after normalization) — still escape it
    code = code.replace("SITE_RULE_PLACEHOLDER", json.dumps(rule))

    manifest = {
        "name": name,
        "version": "1.0.0",
        "description": f"Built in-bot ({ctype}) for {rule}",
        "sites": [rule],
        "entry": "plugin",
        "enabled": True,
        "config": {},
    }

    dest = os.path.join(PLUGINS_DIR, name)
    if os.path.exists(dest):
        shutil.rmtree(dest)
    os.makedirs(dest, exist_ok=True)
    with open(os.path.join(dest, "plugin.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    with open(os.path.join(dest, "plugin.py"), "w", encoding="utf-8") as f:
        f.write(code)
    return {"ok": True, "name": name, "message": f"پلاگین '{name}' ساخته و نصب شد",
            "ctype": ctype}


def test_pattern(site_url: str, pattern: str) -> dict:
    """Fetch the sample URL and count matches. Returns {ok, matches, sample?}."""
    try:
        req = urllib.request.Request(
            site_url, headers={"User-Agent":
                               "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120.0"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            html = resp.read().decode("utf-8", "ignore")
        try:
            pat = re.compile(pattern)
        except re.error as e:
            return {"ok": False, "message": f"regex نامعتبر: {e}"}
        found = pat.findall(html)
        if not found:
            return {"ok": False, "message": "هیچ مقداری با الگو پیدا نشد"}
        sample = found[0] if isinstance(found[0], str) else str(found[0])
        return {"ok": True, "matches": len(found), "sample": sample[:120]}
    except Exception as e:
        return {"ok": False, "message": f"خطا در دریافت صفحه: {e}"}